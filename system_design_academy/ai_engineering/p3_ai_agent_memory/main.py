"""P3 AI Engineering · Agent Memory.

LLMs have no memory between calls. Useful agents need three kinds of memory:

  - Short-term memory: the current chat (last N turns).
  - Long-term memory:  durable facts about the user / world (vector store).
  - Episodic memory:   summaries of past sessions ('last week we worked on X').

This file implements all three with stdlib only. The "vector" store uses
bag-of-words cosine similarity so the demo runs offline.
"""

from __future__ import annotations

import math
import re
from collections import Counter, deque
from dataclasses import dataclass, field


def tokenize(text: str) -> list[str]:
    """Split text into lowercase word tokens."""
    return re.findall(r"[a-z0-9]+", text.lower())


def cosine(a: Counter[str], b: Counter[str]) -> float:
    """Cosine similarity between two bag-of-words vectors."""
    common = set(a) & set(b)
    num = sum(a[t] * b[t] for t in common)
    da = math.sqrt(sum(v * v for v in a.values()))
    db = math.sqrt(sum(v * v for v in b.values()))
    return num / (da * db) if da and db else 0.0


# ---------- the three memory types ---------------------------------------


@dataclass
class ShortTermMemory:
    """Sliding window of the most recent chat turns."""

    capacity: int = 6
    turns: deque[str] = field(default_factory=deque)

    def add(self, role: str, content: str) -> None:
        """Append a turn and drop the oldest when over capacity."""
        self.turns.append(f"{role}: {content}")
        while len(self.turns) > self.capacity:
            self.turns.popleft()

    def render(self) -> str:
        """Return the buffered conversation as a single string."""
        return "\n".join(self.turns)


@dataclass
class LongTermMemory:
    """Tiny vector-ish store of durable facts; supports recall by similarity."""

    facts: list[tuple[str, Counter[str]]] = field(default_factory=list)

    def remember(self, fact: str) -> None:
        """Save a fact alongside its bag-of-words vector."""
        self.facts.append((fact, Counter(tokenize(fact))))

    def recall(self, query: str, top_k: int = 2) -> list[str]:
        """Return the most similar facts to `query`."""
        q = Counter(tokenize(query))
        scored = [(cosine(q, vec), fact) for fact, vec in self.facts]
        scored.sort(reverse=True)
        return [fact for score, fact in scored[:top_k] if score > 0]


@dataclass
class EpisodicMemory:
    """One summary line per past session."""

    summaries: list[str] = field(default_factory=list)

    def record_session(self, summary: str) -> None:
        """Append a session summary to the timeline."""
        self.summaries.append(summary)

    def recent(self, n: int = 2) -> list[str]:
        """Return the last `n` session summaries."""
        return self.summaries[-n:]


# ---------- a small agent that uses all three ----------------------------


@dataclass
class MemoryAgent:
    """Builds a prompt from short-term + long-term + episodic memory."""

    short: ShortTermMemory = field(default_factory=ShortTermMemory)
    long: LongTermMemory = field(default_factory=LongTermMemory)
    episodic: EpisodicMemory = field(default_factory=EpisodicMemory)

    def step(self, user_msg: str) -> str:
        """Produce a prompt and a canned 'reply' for the demo."""
        self.short.add("user", user_msg)
        recalled = self.long.recall(user_msg, top_k=2)
        episodes = self.episodic.recent(2)

        prompt_blocks = []
        if episodes:
            prompt_blocks.append("PAST SESSIONS:\n- " + "\n- ".join(episodes))
        if recalled:
            prompt_blocks.append("RELEVANT FACTS:\n- " + "\n- ".join(recalled))
        prompt_blocks.append("CHAT:\n" + self.short.render())
        prompt = "\n\n".join(prompt_blocks)

        # Mock "LLM" reply: just acknowledge what was recalled.
        reply = (
            f"(I recalled {len(recalled)} fact(s) and {len(episodes)} past summary/ies; "
            f"I would now answer using them.)"
        )
        self.short.add("agent", reply)
        return f"PROMPT SENT TO LLM\n{'-' * 32}\n{prompt}\n{'-' * 32}\nREPLY: {reply}"

    def end_session(self, summary: str) -> None:
        """Persist a one-line summary so the next session can recall it."""
        self.episodic.record_session(summary)
        self.short.turns.clear()


def main() -> None:
    """Seed memory, run two sessions, and show what gets recalled."""
    agent = MemoryAgent()
    for fact in [
        "the user is named Priya",
        "Priya works as a backend engineer in Bengaluru",
        "she prefers Python with type hints and pytest",
        "the user dislikes long autogenerated docstrings",
    ]:
        agent.long.remember(fact)

    print("=== session 1 ===")
    print(agent.step("hi! remind me what tech stack we discussed last time?"))
    print()
    print(agent.step("what is my name and city?"))
    agent.end_session(
        "user asked about tech stack and personal details; reaffirmed Python + Bengaluru"
    )

    print("\n=== session 2 (next day) ===")
    print(agent.step("help me with pytest fixtures"))


if __name__ == "__main__":
    main()
